"""Reproducible Random Forest training pipeline.

    python -m ml.train                         # real experimental data from the backend database
    python -m ml.train --source synthetic      # SYNTHETIC demonstration data (explicitly labelled)
    python -m ml.train --source synthetic --activate

Steps: load -> schema validation -> cleaning (no imputation) -> label validation
-> class-imbalance assessment -> session-grouped held-out split -> grouped CV
hyperparameter search on the training sessions only -> fit -> held-out
evaluation -> serialization (model, metadata, metrics, figures) -> optional
activation (only after integrity, schema, load and baseline checks pass; the
previously active model is kept for rollback).

Leakage control: all readings of a session go to the same side of every split
(their rolling-window features overlap in time); identifiers, timestamps and
labels are never model inputs; preprocessing lives inside the sklearn Pipeline
so it is fitted on training folds only.
"""
from __future__ import annotations

import argparse
import json
import platform
import sqlite3
import sys
import time
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import GridSearchCV, StratifiedGroupKFold
from sklearn.pipeline import Pipeline

from . import datasets
from .evaluate import classification_metrics, feature_importances, majority_baseline, save_figures
from .features import CLASSES, FEATURE_NAMES, SCHEMA_VERSION
from .predict import ModelBundle
from .registry import DEFAULT_ARTIFACTS_DIR, Registry, RegistryError, atomic_write_json, sha256_file

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DB = REPO_ROOT / "backend" / "data" / "landslide.db"
PARAM_GRID = {
    "rf__max_depth": [None, 14],
    "rf__min_samples_leaf": [1, 5],
}
LIMITATIONS = {
    "test_fixture": ["Automated test fixture model; meaningless outside the test suite."],
    "synthetic_demo": [
        "Trained and evaluated on SYNTHETIC data generated by ml/synthetic.py; labels are the generator's scripted "
        "scenario stages, so the metrics measure how well the model recovers that script, not real-world landslide "
        "prediction accuracy.",
        "Use only to demonstrate the software pipeline. Enabled only when LANDSLIDE_DEMO_MODE=true.",
    ],
    "experimental": [
        "Labels are experimenter annotations of a miniature slope model, not real landslide outcomes.",
        "Small numbers of sessions make metrics unstable; a miniature model is not a scaled replica of a real slope.",
        "Not validated for public-safety use.",
    ],
}


class TrainingError(Exception):
    pass


def build_pipeline(seed: int) -> Pipeline:
    features = ColumnTransformer([("features", "passthrough", FEATURE_NAMES)], remainder="drop",
                                 verbose_feature_names_out=False)
    rf = RandomForestClassifier(n_estimators=200, max_features="sqrt", class_weight="balanced_subsample",
                                random_state=seed, n_jobs=-1)
    return Pipeline([("features", features), ("rf", rf)])


def grouped_holdout(df: pd.DataFrame, seed: int, n_splits: int = 5) -> tuple[np.ndarray, np.ndarray, int]:
    """Session-grouped, label-stratified hold-out (~1/n_splits of sessions); prefers a fold containing all classes."""
    sgkf = StratifiedGroupKFold(n_splits=n_splits, shuffle=True, random_state=seed)
    y, groups = df["label"].to_numpy(), df["session_id"].to_numpy()
    best = None
    for fold, (tr, te) in enumerate(sgkf.split(df, y, groups)):
        if set(y[te]) == set(CLASSES):
            return tr, te, fold
        if best is None:
            best = (tr, te, fold)
    return best


def train(source: str, *, db_path: Path, synthetic_path: Path, artifacts: Path, seed: int, activate: bool,
          version: str | None = None, quiet: bool = False, cv_splits: int = 4, n_estimators: int = 200,
          provenance_override: str | None = None) -> dict:
    """provenance_override exists for automated tests (\"test_fixture\" artifacts)."""
    say = (lambda *a: None) if quiet else print
    started = time.time()
    if source == "synthetic":
        raw, sha = datasets.load_synthetic(synthetic_path)
        provenance, data_path = "synthetic_demo", synthetic_path
    elif source == "experimental":
        raw, sha = datasets.load_experimental(db_path)
        provenance, data_path = "experimental", db_path
    else:
        raise TrainingError(f"unknown source {source}")
    if provenance_override:
        provenance = provenance_override
    say(f"[1/9] loaded {len(raw)} rows from {source} ({data_path})")

    df, report = datasets.validate_and_clean(raw, source, str(Path(data_path).relative_to(REPO_ROOT))
                                             if Path(data_path).is_relative_to(REPO_ROOT) else str(data_path), sha)
    say(f"[2/9] validated: {report.rows_used} usable rows, {report.sessions} sessions; dropped "
        f"missing={report.dropped_missing} out_of_range={report.dropped_out_of_range} "
        f"duplicates={report.dropped_duplicates} bad_label={report.dropped_bad_label}")
    say(f"      class counts {report.class_counts}; sessions per class {report.sessions_per_class}")
    problems = datasets.sufficiency_problems(report)
    if problems:
        raise TrainingError("INSUFFICIENT_DATA for a 4-class model:\n  - " + "\n  - ".join(problems)
                            + "\nCollect and annotate more real sessions (see docs/ML.md).")
    counts = np.array([report.class_counts[c] for c in CLASSES])
    imbalance = float(counts.max() / max(counts.min(), 1))
    say(f"[3/9] class imbalance ratio (largest/smallest) = {imbalance:.1f}; using class_weight=balanced_subsample")

    train_idx, test_idx, fold = grouped_holdout(df, seed)
    train_df, test_df = df.iloc[train_idx], df.iloc[test_idx]
    overlap = set(train_df["session_id"]) & set(test_df["session_id"])
    if overlap:
        raise TrainingError(f"session leakage between train and test: {sorted(overlap)[:5]}")
    say(f"[4/9] held-out split: {train_df['session_id'].nunique()} train sessions ({len(train_df)} rows), "
        f"{test_df['session_id'].nunique()} test sessions ({len(test_df)} rows); no shared sessions")

    X_tr, y_tr, g_tr = train_df[FEATURE_NAMES], train_df["label"].to_numpy(), train_df["session_id"].to_numpy()
    X_te, y_te = test_df[FEATURE_NAMES], test_df["label"].to_numpy()
    pipeline = build_pipeline(seed)
    pipeline.set_params(rf__n_estimators=n_estimators)
    cv = StratifiedGroupKFold(n_splits=cv_splits, shuffle=True, random_state=seed)
    search = GridSearchCV(pipeline, PARAM_GRID, scoring="f1_macro", cv=cv, n_jobs=1, refit=True,
                          return_train_score=False)
    say(f"[5/9] grouped {cv_splits}-fold CV grid search over {len(PARAM_GRID['rf__max_depth']) * len(PARAM_GRID['rf__min_samples_leaf'])} settings")
    search.fit(X_tr, y_tr, groups=g_tr)
    model = search.best_estimator_
    cv_results = [
        {"params": {k.replace("rf__", ""): v for k, v in p.items()}, "mean_f1_macro": float(m), "std_f1_macro": float(s)}
        for p, m, s in zip(search.cv_results_["params"], search.cv_results_["mean_test_score"],
                           search.cv_results_["std_test_score"])
    ]
    say(f"      best {search.best_params_} CV macro-F1 {search.best_score_:.3f}")

    y_pred = model.predict(X_te)
    test_metrics = classification_metrics(y_te, y_pred)
    baseline = majority_baseline(y_tr, y_te)
    say(f"[6/9] held-out: accuracy {test_metrics['accuracy']:.3f} balanced {test_metrics['balanced_accuracy']:.3f} "
        f"macro-F1 {test_metrics['macro']['f1']:.3f} (majority baseline macro-F1 {baseline['macro']['f1']:.3f})")
    importance = feature_importances(model, X_te, y_te, seed)

    stamp = time.strftime("%Y%m%d-%H%M%S", time.gmtime())
    version = version or f"rf-{ {'synthetic_demo': 'synthetic', 'experimental': 'exp'}.get(provenance, 'test') }-{stamp}"
    registry = Registry(artifacts)
    out_dir = registry.artifact_dir(version)
    if out_dir.exists():
        raise TrainingError(f"artifact {version} already exists")
    out_dir.mkdir(parents=True)
    joblib.dump(model, out_dir / "model.joblib", compress=3)

    rf = model.named_steps["rf"]
    hyper = {k: v for k, v in rf.get_params().items() if k in (
        "n_estimators", "max_depth", "min_samples_leaf", "max_features", "class_weight", "random_state", "criterion")}
    title = {"synthetic_demo": "SYNTHETIC demonstration data", "experimental": "real experimental data"}.get(provenance, "test fixture")
    metrics = {
        "model_version": version,
        "provenance": provenance,
        "data_note": LIMITATIONS[provenance][0],
        "dataset": report.as_dict(),
        "class_imbalance_ratio": imbalance,
        "split": {
            "method": f"StratifiedGroupKFold(n_splits=5, shuffle=True, random_state={seed}) by session; fold {fold} held out",
            "train_sessions": int(train_df["session_id"].nunique()),
            "test_sessions": int(test_df["session_id"].nunique()),
            "train_rows": int(len(train_df)),
            "test_rows": int(len(test_df)),
            "test_session_ids": sorted(test_df["session_id"].unique().tolist()),
        },
        "cross_validation": {
            "method": f"StratifiedGroupKFold(n_splits={cv_splits}) on training sessions only",
            "scoring": "f1_macro",
            "best_params": {k.replace("rf__", ""): v for k, v in search.best_params_.items()},
            "best_mean_f1_macro": float(search.best_score_),
            "results": cv_results,
        },
        "test": test_metrics,
        "majority_class_baseline": baseline,
        "feature_importance": importance,
        "training_seconds": round(time.time() - started, 1),
    }
    metrics["figures"] = save_figures(metrics, out_dir, title)
    atomic_write_json(out_dir / "metrics.json", metrics)
    metadata = {
        "model_version": version,
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "provenance": provenance,
        "algorithm": "RandomForestClassifier (scikit-learn Pipeline: ColumnTransformer passthrough -> RF)",
        "feature_schema_version": SCHEMA_VERSION,
        "features": FEATURE_NAMES,
        "classes": [str(c) for c in model.classes_],
        "hyperparameters": hyper,
        "dataset": {"source": source, "path": report.path, "sha256": sha, "rows_used": report.rows_used,
                    "sessions": report.sessions, "class_counts": report.class_counts},
        "summary_metrics": {"accuracy": test_metrics["accuracy"], "balanced_accuracy": test_metrics["balanced_accuracy"],
                            "macro_f1": test_metrics["macro"]["f1"]},
        "limitations": LIMITATIONS[provenance],
        "seed": seed,
        "environment": {"python": platform.python_version(), "sklearn": sklearn.__version__,
                        "numpy": np.__version__, "pandas": pd.__version__},
        "artifact_sha256": sha256_file(out_dir / "model.joblib"),
    }
    atomic_write_json(out_dir / "metadata.json", metadata)
    say(f"[7/9] saved artifact {out_dir}")

    # ---- validation before activation
    checks = []
    try:
        registry.verify(version)
        checks.append("integrity: sha256 matches")
        bundle = ModelBundle.load(registry, version)
        checks.append("load: feature schema and classes compatible")
        sample = test_df.iloc[0][FEATURE_NAMES].to_dict()
        bundle.predict(sample)
        checks.append("inference: predict_proba on a held-out row")
    except (RegistryError, ValueError) as exc:
        raise TrainingError(f"candidate failed validation: {exc}") from exc
    beats_baseline = test_metrics["macro"]["f1"] > baseline["macro"]["f1"] + 0.05
    checks.append(f"held-out macro-F1 {'exceeds' if beats_baseline else 'DOES NOT exceed'} majority baseline + 0.05")
    say("[8/9] validation: " + "; ".join(checks))

    activated = False
    if activate:
        if not beats_baseline:
            say("      NOT activated: the model does not beat the majority-class baseline")
        else:
            registry.activate(version, reason=f"trained on {source}")
            activated = True
            say(f"      ACTIVATED {version} (previous model kept for rollback: python -m ml.registry rollback)")
    else:
        say("      candidate only (use --activate, or: python -m ml.registry activate " + version + ")")

    _record_run(db_path, version, provenance, sha, report.rows_used,
                "active" if activated else "candidate", metrics)
    say(f"[9/9] done in {time.time() - started:.0f} s")
    return {"version": version, "activated": activated, "metrics": metrics, "checks": checks}


def _record_run(db_path: Path, version: str, provenance: str, sha: str, n: int, status: str, metrics: dict) -> None:
    """Training run metadata in the backend database (if it exists and is migrated)."""
    if not Path(db_path).exists():
        return
    try:
        conn = sqlite3.connect(str(db_path), timeout=10)
        try:
            if not conn.execute("SELECT 1 FROM sqlite_master WHERE name='training_runs'").fetchone():
                return
            summary = {k: metrics["test"][k] for k in ("accuracy", "balanced_accuracy")}
            summary["macro_f1"] = metrics["test"]["macro"]["f1"]
            conn.execute(
                "INSERT OR REPLACE INTO training_runs (created_at, model_version, provenance, dataset_sha256, n_samples,"
                " status, metrics_json, notes) VALUES (?,?,?,?,?,?,?,?)",
                (time.time(), version, provenance, sha, n, status, json.dumps(summary), metrics["data_note"]),
            )
            conn.commit()
        finally:
            conn.close()
    except sqlite3.Error as exc:
        print(f"warning: training run not recorded in the database: {exc}", file=sys.stderr)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Train the four-sensor Random Forest")
    parser.add_argument("--source", choices=["experimental", "synthetic"], default="experimental")
    parser.add_argument("--db", default=str(DEFAULT_DB), help="backend database (experimental source)")
    parser.add_argument("--synthetic-csv", default=str(datasets.SYNTHETIC_DEFAULT))
    parser.add_argument("--artifacts", default=str(DEFAULT_ARTIFACTS_DIR))
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--activate", action="store_true", help="activate the model if validation passes")
    args = parser.parse_args(argv)
    try:
        result = train(args.source, db_path=Path(args.db), synthetic_path=Path(args.synthetic_csv),
                       artifacts=Path(args.artifacts), seed=args.seed, activate=args.activate)
    except (TrainingError, FileNotFoundError, RuntimeError) as exc:
        print(f"\nTRAINING STOPPED: {exc}", file=sys.stderr)
        return 1
    if result["activated"]:
        print("Restart the backend (or POST /api/model/reload with the admin token) to use the new model.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
